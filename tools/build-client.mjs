/** Wrap src/client.js in the DSH ModuleLoader factory and syntax-check the result. */
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const SRC = join(ROOT, 'src', 'client.js')
const OUT = join(ROOT, 'lib', 'client.js')
const PACKAGE = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'))

const body = readFileSync(SRC, 'utf8')
if (!/return\s+\{\s*inject\s*,\s*apply\s*\}\s*$/.test(body.trim())) {
  throw new Error('src/client.js must end with `return { inject, apply }`')
}

const output = `/**
 * Generated by tools/build-client.mjs. Do not edit lib/client.js directly.
 * Browser half of ${PACKAGE.name}; the module id must equal the package name.
 */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(PACKAGE.name)},
  factory(require) {
${body}
  },
})
`
writeFileSync(OUT, output, 'utf8')
execFileSync(process.execPath, ['--check', OUT], { stdio: 'inherit' })
console.log(`[client] wrote ${OUT} (${Buffer.byteLength(output)} bytes)`)
