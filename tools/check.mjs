/** Static checks that keep the client safe to load and the package publishable. */
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, statSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const errors = []
const read = (name) => readFileSync(join(ROOT, name), 'utf8')

const packageJson = JSON.parse(read('package.json'))
const client = read('lib/client.js')
const srcClient = read('src/client.js')
const host = read('src/host.js')
const patch = read('cordis.patch.yml')
const packIds = ['primary', 'ket', 'pet', 'gaokao', 'cet4', 'cet6', 'kaoyan']

if (packageJson.name !== 'dsh-word-veil') errors.push('package name must be dsh-word-veil')
if (!packageJson.dsh?.bundle?.patch) errors.push('missing dsh.bundle.patch')
if (!packageJson.dsh?.client?.platform) errors.push('missing dsh.client.platform')
if (!packageJson.dsh?.compatibility?.dshReleases) errors.push('missing validated dshReleases compatibility')
if (!packageJson.exports?.['./client']) errors.push('missing ./client export')
if (!packageJson.files?.includes('src')) errors.push('files must include src for lib/index.js re-export')
if (!patch.includes('id: word-veil')) errors.push('cordis.patch.yml missing word-veil row')
for (const file of ['packs/index.json', ...packIds.map((id) => `packs/${id}.json`), 'icon.svg', 'locale/zh.json', 'locale/en.json', 'docs/DETAIL.md', 'docs/PACKS.md', 'docs/DATA.md']) {
  if (!existsSync(join(ROOT, file))) errors.push(`missing ${file}`)
}
for (const file of packIds.map((id) => `packs/${id}.json`)) {
  try {
    const pack = JSON.parse(read(file))
    if (!Array.isArray(pack.words) || pack.words.length !== pack.wordCount) errors.push(`${file} count mismatch`)
    if (!pack.source || !pack.license) errors.push(`${file} missing source/license`)
  } catch (error) {
    errors.push(`${file}: ${error instanceof Error ? error.message : String(error)}`)
  }
}
try {
  const index = JSON.parse(read('packs/index.json'))
  const ids = index.map((pack) => pack.id)
  if (JSON.stringify(ids) !== JSON.stringify(packIds)) errors.push(`packs/index.json ids ${ids.join(',')} != ${packIds.join(',')}`)
} catch (error) {
  errors.push(`packs/index.json: ${error instanceof Error ? error.message : String(error)}`)
}

const expectedClient = `/**
 * Generated by tools/build-client.mjs. Do not edit lib/client.js directly.
 * Browser half of ${packageJson.name}; the module id must equal the package name.
 */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(packageJson.name)},
  factory(require) {
${srcClient}
  },
})
`
if (client !== expectedClient) errors.push('lib/client.js is stale; run node tools/build-client.mjs')

if ((client.match(/__ModuleLoader__\.load/g) ?? []).length !== 1) errors.push('client must load exactly one module')
if ((client.match(/require\(/g) ?? []).length !== 1 || !client.includes("require('react')")) errors.push('client must only require react')
for (const forbidden of ['eval(', 'new Function', 'XMLHttpRequest', 'WebSocket']) {
  if (client.includes(forbidden)) errors.push(`client contains forbidden token: ${forbidden}`)
}
if (/[A-Za-z]:\\/.test(client)) errors.push('client contains an absolute Windows path')
if (/https?:\/\//.test(client)) errors.push('client must not contain external URLs')
if (!client.includes("inject = ['slots', 'locale', 'layout']")) errors.push('client inject declaration is wrong')
if (client.includes('packs/cet4.json')) errors.push('client must not embed pack data')

if ((host.match(/https?:\/\/(?!localhost)[^\s'"`)]+/g) ?? []).length > 0) errors.push('host must not call external URLs at runtime')
if (statSync(join(ROOT, 'lib/client.js')).size > 1024 * 1024) errors.push('client bundle is unexpectedly large (packs embedded?)')

try {
  for (const file of ['lib/client.js', 'lib/index.js', 'src/host.js', 'tools/build-packs.mjs', 'tools/fetch-wordbank.mjs', 'tools/build-client.mjs', 'tools/lib/pack-build.mjs']) {
    execFileSync(process.execPath, ['--check', join(ROOT, file)], { stdio: 'pipe' })
  }
} catch (error) {
  errors.push(`syntax check: ${error instanceof Error ? error.message : String(error)}`)
}

if (errors.length > 0) {
  console.error(`[check] ${errors.length} issue(s)`)
  for (const error of errors) console.error(` - ${error}`)
  process.exitCode = 1
} else {
  console.log('[check] ok')
}
